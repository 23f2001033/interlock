"""12-month Base / Growth model for the cfo.ai plan, driven by Interlock's MEASURED cost per check.

Outputs business-plan/model.csv (one row per month and scenario) and business-plan/model_summary.md.
Every assumption is a named constant below, and these are the same drivers we enter into cfo.ai.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "business-plan"

# --- measured (eval/results/v2.3-*.json: $0.38 for 8 checked pairs) ---
v23 = sorted((ROOT / "eval" / "results").glob("v2.3-*.json"))[-1]
m = json.loads(v23.read_text(encoding="utf-8"))["metrics"]
COST_PER_CHECK = m["cost_usd"] / m["pairs"]          # USD per checked pair

# --- assumptions ---
PRICE_PER_DEV = 30.0                # USD / developer / month (Team plan)
CHECKS_PER_DEV = 80                 # ~40 agent PRs per dev per month x ~2 pair checks per PR
HOSTING_PER_CUSTOMER = 10.0         # USD / month
STARTING_CASH = 50_000.0            # USD (founder savings / angel), editable in cfo.ai
OPEX_BASE = {"founder stipend": 3_000, "tools & services": 400, "base infra": 300, "marketing & community": 800}
FOUNDING_ENGINEER = 6_000           # USD / month, hired the month after MRR first reaches $15k
HIRE_AT_MRR = 15_000
PILOT_MONTHS = 3                    # months 1-3: free design-partner pilots (costs, no revenue)
PILOT_CUSTOMERS = 3
SCENARIOS = {
    # customers at month 12, developers per customer, ramp exponent (1 = linear)
    "Base": {"customers_m12": 40, "devs": 10, "curve": 1.0},
    "Growth": {"customers_m12": 120, "devs": 12, "curve": 1.4},
}


def run(name: str, s: dict) -> list[dict]:
    rows, cash, hired = [], STARTING_CASH, False
    for month in range(1, 13):
        if month <= PILOT_MONTHS:
            customers, paying = PILOT_CUSTOMERS, 0
        else:
            customers = paying = max(PILOT_CUSTOMERS, round(s["customers_m12"] * ((month - PILOT_MONTHS) / (12 - PILOT_MONTHS)) ** s["curve"]))
        devs = customers * s["devs"]
        mrr = paying * s["devs"] * PRICE_PER_DEV
        cogs = devs * CHECKS_PER_DEV * COST_PER_CHECK + customers * HOSTING_PER_CUSTOMER
        opex = sum(OPEX_BASE.values()) + (FOUNDING_ENGINEER if hired else 0)
        net = mrr - cogs - opex
        cash += net
        if mrr >= HIRE_AT_MRR:
            hired = True
        rows.append({"scenario": name, "month": month, "customers": customers, "developers": devs,
                     "mrr": round(mrr), "cogs": round(cogs), "gross_profit": round(mrr - cogs),
                     "gross_margin_pct": round(100 * (mrr - cogs) / mrr, 1) if mrr else None,
                     "opex": round(opex), "net_burn": round(-net) if net < 0 else 0,
                     "net_income": round(net), "cash_end": round(cash)})
    return rows


if __name__ == "__main__":
    all_rows = [r for name, s in SCENARIOS.items() for r in run(name, s)]
    with open(OUT / "model.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(all_rows[0]))
        w.writeheader()
        w.writerows(all_rows)
    lines = [f"# Model summary (generated by `scripts/business_model.py`)\n",
             f"Measured cost per checked pair: **${COST_PER_CHECK:.4f}** (from `{v23.name}`). Price ${PRICE_PER_DEV:.0f}/developer/month. "
             f"{CHECKS_PER_DEV} checks/developer/month. Hosting ${HOSTING_PER_CUSTOMER:.0f}/customer. Starting cash ${STARTING_CASH:,.0f}. "
             f"Months 1-{PILOT_MONTHS}: {PILOT_CUSTOMERS} free design-partner pilots (costs, no revenue). "
             f"Base opex ${sum(OPEX_BASE.values()):,}/month, plus a founding engineer (${FOUNDING_ENGINEER:,}) "
             f"once MRR reaches ${HIRE_AT_MRR:,}.\n"]
    for name in SCENARIOS:
        rows = [r for r in all_rows if r["scenario"] == name]
        low = min(rows, key=lambda r: r["cash_end"])
        breakeven = next((r["month"] for r in rows if r["net_income"] >= 0), None)
        lines += [f"\n## {name}\n", "| Month | Customers | Devs | MRR | COGS | Gross margin | Opex | Net | Cash |",
                  "|---|---|---|---|---|---|---|---|---|"]
        lines += [f"| {r['month']} | {r['customers']} | {r['developers']} | ${r['mrr']:,} | ${r['cogs']:,} | {(str(r['gross_margin_pct']) + '%') if r['gross_margin_pct'] is not None else 'pilot'} | "
                  f"${r['opex']:,} | ${r['net_income']:,} | ${r['cash_end']:,} |" for r in rows]
        lines.append(f"\nBreak-even month: **{breakeven or 'not within 12 months'}** · lowest cash: **${low['cash_end']:,}** (month {low['month']}) · "
                     f"month-12 ARR: **${rows[-1]['mrr'] * 12:,}**.\n")
    (OUT / "model_summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
